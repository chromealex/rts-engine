#!/usr/bin/env python3
"""Builds templates/wildfire (grid fields sample, docs/fields.md) from templates/skirmish: the same Iron and Gold
rules + map, plus rules "fields" (forest fire with a fuel layer, per-player creep around halls and barracks) and
the map's initial fuel (RLE: tree cells 18, other cells 0) and two smouldering forest fires.
Usage: python3 templates/_tools/wildfire.py   (rewrites templates/wildfire/rules.json, maps/forest.json, game.json)
"""
import json, os, re, shutil

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SRC = os.path.join(ROOT, 'skirmish')
DST = os.path.join(ROOT, 'wildfire')


def load(p):
    return json.loads(re.sub(r'^\s*//.*$', '', open(p).read(), flags=re.M))


def rle(vals):
    out, i = [], 0
    while i < len(vals):
        j = i + 1
        while j < len(vals) and vals[j] == vals[i]:
            j += 1
        out.append(str(vals[i]) + ('*%d' % (j - i) if j - i > 1 else ''))
        i = j
    return ' '.join(out)


def main():
    os.makedirs(DST, exist_ok=True)
    for d in ('fonts', 'fx', 'lang', 'ui'):
        if os.path.isdir(os.path.join(DST, d)):
            shutil.rmtree(os.path.join(DST, d))
        shutil.copytree(os.path.join(SRC, d), os.path.join(DST, d))
    shutil.copy(os.path.join(SRC, 'audio.json'), os.path.join(DST, 'audio.json'))
    rules = load(os.path.join(SRC, 'rules.json'))
    t = rules['types']
    t['tree'] = {"name": "Tree", "tags": ["tree"], "structure": {"footprint": [1, 1]}, "health": {"max": 40},
                 "countsForVictory": False, "resourceNode": {"resource": "wood", "amount": 80}, "view": {"shape": "tree"}}
    for k in ('townhall', 'barracks'):
        t[k]['field'] = {"creep": {"emit": 60, "radius": 5 if k == 'townhall' else 3, "mode": "max", "period": 20}}
    t['catapult']['weapons'][0]['onHit'] = {"chance": 0.2, "effects": [{"type": "field", "field": "fire", "max": 100}]}
    rules['playerAbilities'] = [{"id": "ignite", "name": "Ignite", "smart": "densestEnemy", "target": "point", "cooldown": 60,
                                 "initialCooldown": 90, "cost": {"gold": 50},
                                 "effects": [{"type": "field", "field": "fire", "max": 100, "radius": 1.5}]}]
    rules['damageTable']['fire'] = {"fortified": 0.5}
    rules['fields'] = {
        "fuel": {"type": "int", "min": 0, "max": 100, "view": {"show": False}},
        "fire": {"type": "int", "min": 0, "max": 100,
                 "kernels": [
                     {"type": "spread", "period": 10, "above": 1, "set": 100, "chance": 0.12, "fuelChance": 0.01,
                      "fuel": {"field": "fuel", "min": 1}},
                     {"type": "consume", "period": 10, "fuel": "fuel", "amount": 1, "above": 1, "out": 0}],
                 "effects": [
                     {"type": "damage", "above": 1, "perSecond": 8, "damageType": "fire", "period": 10},
                     {"type": "speed", "above": 1, "mul": 0.6},
                     {"type": "reveal", "above": 50}],
                 "view": {"preset": "fire", "particles": {"effect": "fire_smoke", "above": 50, "max": 20, "every": 1.2}}},
        "creep": {"type": "int", "min": 0, "max": 100, "perPlayer": True, "resolution": 2,
                  "kernels": [{"type": "diffuse", "period": 20, "rate": 0.25}, {"type": "decay", "period": 20, "amount": 2}],
                  "effects": [
                      {"type": "speed", "above": 30, "mul": 1.15, "who": "own"},
                      {"type": "yield", "above": 30, "resource": "gold", "perSecond": 0.01},
                      {"type": "reveal", "above": 20}],
                  "view": {"preset": "creep", "height": 0.05}}}
    with open(os.path.join(DST, 'rules.json'), 'w') as f:
        f.write('// Wildfire: Iron and Gold + grid fields (docs/fields.md). Generated by templates/_tools/wildfire.py from\n'
                '// templates/skirmish: forests burn (fire + fuel fields), halls and barracks spread creep (per-player field).\n')
        json.dump(rules, f, indent=1)
        f.write('\n')
    m = load(os.path.join(SRC, 'maps', 'valley.json'))
    w, h = m['size']
    fuel = [0] * (w * h)
    for e in m['entities']:
        if e['type'] == 'tree':
            x, z = int(e['pos'][0]), int(e['pos'][1])
            if 0 <= x < w and 0 <= z < h:
                fuel[z * w + x] = 18
    # two smouldering fires in forests away from the bases (mirror positions)
    trees = [(int(e['pos'][0]), int(e['pos'][1])) for e in m['entities'] if e['type'] == 'tree']
    fires = []
    for target in ((22, 10), (w - 23, h - 11)):
        best = min(trees, key=lambda p: (p[0] - target[0]) ** 2 + (p[1] - target[1]) ** 2)
        fires.append({"circle": [best[0] + 0.5, best[1] + 0.5, 1.2], "value": 100})
    m['name'] = 'Burning Valley'
    m['gridFields'] = {"fuel": {"values": rle(fuel)}, "fire": {"fill": fires}}
    os.makedirs(os.path.join(DST, 'maps'), exist_ok=True)
    with open(os.path.join(DST, 'maps', 'forest.json'), 'w') as f:
        json.dump(m, f, indent=1)
        f.write('\n')
    game = {"name": "Wildfire", "description": "Grid fields sample: forest fires and creep (docs/fields.md).",
            "id": "com.rtsengine.wildfire", "version": "0.1.0", "build": 1, "module": "rts", "sourceLanguage": "en",
            "languages": ["en", "ru"], "rules": "rules.json",
            "maps": [{"file": "maps/forest.json", "title": "Burning Valley (1v1)"}],
            "lighting": {"time": 0.4, "dayLength": 480, "clouds": 0.4}, "orientation": "landscape"}
    with open(os.path.join(DST, 'game.json'), 'w') as f:
        f.write('// Grid fields sample (generated by templates/_tools/wildfire.py).\n')
        json.dump(game, f, indent=2)
        f.write('\n')


if __name__ == '__main__':
    main()
